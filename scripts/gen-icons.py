"""Regenerates src/components/Icon.tsx from Remix Icon SVGs (UI icons only; the
Remix Icon License forbids using them as an app icon/logo).

Usage:  python3 scripts/gen-icons.py <path-to-extracted-remixicon-package>
Get the package with:  npm pack remixicon@4.9.1 && tar xzf remixicon-4.9.1.tgz
Add an icon by appending its file name (without .svg) to NAMES."""
import json, pathlib, re, sys

NAMES = [
    "arrow-left-s-line", "arrow-right-s-line", "arrow-down-s-line", "refresh-line", "logout-box-r-line",
    "search-line", "close-circle-fill", "login-box-line", "record-circle-fill", "map-pin-2-line", "check-line",
    "sun-line", "moon-line", "contrast-2-line",
]

root = pathlib.Path(sys.argv[1]) / "icons"
entries = []
for n in NAMES:
    svg = next(root.rglob(f"{n}.svg")).read_text()
    assert 'viewBox="0 0 24 24"' in svg, n
    assert set(re.findall(r"<(\w+)", svg)) <= {"svg", "path"}, n
    paths = re.findall(r'\sd="([^"]+)"', svg)
    assert paths and all(re.fullmatch(r"[0-9MLHVCSQTAZmlhvcsqtaz .,\-eE]+", p) for p in paths), n
    entries.append(f"  '{n}': {json.dumps(paths)},")

pathlib.Path("src/components/Icon.tsx").write_text("""// GENERATED by scripts/gen-icons.py — edit NAMES there instead of this file.
// Remix Icon (https://remixicon.com, v4.9.1, Remix Icon License v1.0) path data,
// rendered with react-native-svg so the same component works on web and native.
import Svg, { Path } from 'react-native-svg';

const ICONS = {
%s
} as const;

export type IconName = keyof typeof ICONS;

type Props = { name: IconName; size?: number; color?: string };

export function Icon({ name, size = 20, color = '#111827' }: Props) {
  return (
    // Decorative: the surrounding button carries the accessibility label.
    // (Don't pass `accessible` here: react-native-svg forwards it to the DOM on web.)
    <Svg width={size} height={size} viewBox="0 0 24 24" fill={color}>
      {ICONS[name].map((d, i) => (
        <Path key={i} d={d} />
      ))}
    </Svg>
  );
}
""" % "\n".join(entries))
print(f"wrote {len(entries)} icons")
